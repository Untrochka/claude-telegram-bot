// Фиксированные шаблоны для intent, которые можно отправлять автоматически
// без доверия свободному тексту модели (refusal, soft_no, examples).
// По 2-3 варианта на каждый, чтобы одинаковым клиентам не приходило слово в слово.

const REFUSAL = [
  "Понял, спасибо, что ответили. Если в будущем понадобится каталог или удобная запись для клиентов — пишите, буду рад помочь. Хорошего дня!",
  "Хорошо, принял. Если что-то в этом духе понадобится позже — обращайтесь. Хорошего дня!",
  "Понял, спасибо за ответ. Если планы поменяются — буду рад помочь. Всего доброго!",
];

const SOFT_NO = [
  "Хорошо, спасибо! Если появятся вопросы — пишите.",
  "Понял, не торопитесь. Если понадобится — я на связи.",
  "Хорошо 👌. Если надумаете — пишите в любое время.",
];

const EXAMPLES_CATALOG = [
  "Мои работы можно посмотреть здесь: https://untra.dev. Каталог для вас пока в формате макета — могу показать, как он будет выглядеть, на коротком созвоне на 10 минут.",
  "Вот мои работы: https://untra.dev. Могу собрать макет под ваш случай и показать на коротком созвоне, минут на 10.",
];

const EXAMPLES_BARBER = [
  "Вот демо, можно самому попробовать записаться: https://t.me/test_barber_reserv_bot. Под вас поменяю имя, цвета и услуги, запуск за 1 день.",
  "Демо здесь: https://t.me/test_barber_reserv_bot, можно записаться и посмотреть, как это работает. Под вас настрою за 1 день.",
];

function pick(list) {
  return list[Math.floor(Math.random() * list.length)];
}

// intent: "refusal" | "soft_no" | "examples". Для examples важен product
// ("barber" -> демо барбера, иначе -> каталог). Возвращает null, если для
// этого intent шаблонов нет (значит текст берём из свободного ответа модели).
export function getTemplate(intent, product) {
  if (intent === "refusal") return pick(REFUSAL);
  if (intent === "soft_no") return pick(SOFT_NO);
  if (intent === "examples") return pick(product === "barber" ? EXAMPLES_BARBER : EXAMPLES_CATALOG);
  return null;
}
