// Случайная строка, не такая же, как прошлая (индекс хранится в state).
export function pickCalm() {
  const last = getAgentValue("calmLast", -1);
  let i = Math.floor(Math.random() * CALM_LINES.length);
  if (CALM_LINES.length > 1 && i === last) i = (i + 1) % CALM_LINES.length;
  setAgentValue("calmLast", i);
  return CALM_LINES[i];
}
